#!/usr/bin/env python3
"""Generates ifsmb-wordmark.scad from the path in ../institut/ifsmb-logo-badge.svg.

Coordinates stay in SVG units, only Y is mirrored (OpenSCAD: Y points up).
Quadratic Bezier curves (Q) are split into line segments.
Usage: python3 wordmark_from_svg.py
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SVG = os.path.join(HERE, "..", "institut", "ifsmb-logo-badge.svg")
OUT = os.path.join(HERE, "ifsmb-wordmark.scad")
STEPS = 8  # segments per curve

d = re.search(r'<path fill="#16161d" d="([^"]+)"', open(SVG).read()).group(1)
tokens = re.findall(r"[MLHVQZ]|-?\d*\.?\d+", d)

contours, cur, i, cmd = [], [], 0, None
x = y = 0.0
def num():
    global i
    v = float(tokens[i]); i += 1; return v
while i < len(tokens):
    if re.match(r"[A-Z]", tokens[i]):
        cmd = tokens[i]; i += 1
    if cmd == "M":
        if cur: contours.append(cur)
        x, y = num(), num(); cur = [(x, y)]; cmd = "L"
    elif cmd == "L":
        x, y = num(), num(); cur.append((x, y))
    elif cmd == "H":
        x = num(); cur.append((x, y))
    elif cmd == "V":
        y = num(); cur.append((x, y))
    elif cmd == "Q":
        cx, cy, ex, ey = num(), num(), num(), num()
        for k in range(1, STEPS + 1):
            t = k / STEPS
            cur.append(((1-t)**2*x + 2*(1-t)*t*cx + t*t*ex,
                        (1-t)**2*y + 2*(1-t)*t*cy + t*t*ey))
        x, y = ex, ey
    elif cmd == "Z":
        if cur: contours.append(cur); cur = []
        cmd = None
if cur: contours.append(cur)

pts, paths = [], []
for c in contours:
    if c[0] == c[-1]: c = c[:-1]
    paths.append(list(range(len(pts), len(pts) + len(c))))
    pts += c

with open(OUT, "w") as f:
    f.write("// Generated by wordmark_from_svg.py from ../institut/ifsmb-logo-badge.svg – do not edit by hand.\n")
    f.write("// Wordmark \"IfsMB\" in SVG units, Y mirrored (SVG point (x, y) -> (x, -y)).\n")
    f.write("module ifsmb_wordmark() polygon(points = [\n")
    f.write(",\n".join(f"  [{px:.2f}, {-py:.2f}]" for px, py in pts))
    f.write("\n], paths = [\n")
    f.write(",\n".join("  [" + ", ".join(map(str, p)) + "]" for p in paths))
    f.write("\n]);\n")
print(f"{len(contours)} Konturen, {len(pts)} Punkte -> {OUT}")  # output for people: German
